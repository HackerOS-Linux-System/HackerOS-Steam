import esbuild from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { solidPlugin } from 'esbuild-plugin-solid';

const watch = process.argv.includes('--watch');

// The H# binary must run from anywhere (it is linked statically and installed as one file), so the
// UI is embedded into it: index.html + style.css + dist/app.js become string literals in
// ../src/assets.h# (see main.h#, `app::load_html_str`). Nothing is read from disk at run time.
const hsharpLiteral = (s) =>
  '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\{/g, '{{').replace(/\}/g, '}}')
         .replace(/\r/g, '').replace(/\n/g, '\\n').replace(/\t/g, '\\t') + '"';

function writeAssets() {
  const js = readFileSync('dist/app.js', 'utf8').replace(/<\/script/gi, '<\\/script');
  const css = readFileSync('style.css', 'utf8');
  let html = readFileSync('index.html', 'utf8');
  html = html.replace('</body>', () => '<script>' + js + '</script></body>');
  // silver treats `{{…}}` in HTML as a template binding — the bundle must not contain any.
  if (js.includes('{{')) throw new Error('dist/app.js contains "{{" — silver would read it as a template binding');
  writeFileSync('../src/assets.h#',
    ';; GENERATED by frontend/build.mjs (npm run build) — do not edit.\n' +
    ';; The whole UI (HTML + CSS + the esbuild bundle) embedded as strings, so the binary needs no files next to it.\n\n' +
    'pub fn html() -> string is\n    return ' + hsharpLiteral(html) + '\nend\n\n' +
    'pub fn css() -> string is\n    return ' + hsharpLiteral(css) + '\nend\n');
  console.log('embedded UI → ../src/assets.h#');
}
const ctx = await esbuild.context({
  entryPoints: ['src/index.tsx'],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  plugins: [solidPlugin()],      // babel-preset-solid: JSX -> fine-grained DOM instructions
  conditions: ['browser'],       // solid-js "browser" build (client runtime, not the SSR one)
  define: { 'process.env.NODE_ENV': watch ? '"development"' : '"production"' },
  minify: !watch,
  sourcemap: false,
  outfile: 'dist/app.js',
  logLevel: 'info',
});
if (watch) {
  await ctx.watch(); console.log('watching for changes…');
  const { watch: fsWatch } = await import('node:fs');
  fsWatch('dist', () => { try { writeAssets(); } catch {} });
} else { await ctx.rebuild(); await ctx.dispose(); writeAssets(); }
